from scipy.stats import linregress
from scipy.stats import spearmanr, pearsonr

enh_50kb_summary = (
    enhancer_fountain_hits_60
    .query("enhancer_distance_to_base_bp <= 50000")
    .groupby("Fountain index", as_index=False)
    .agg(
        **{
            "Fountain Score": ("Fountain Score", "first"),
            "n_enhancers_50kb": ("enhancer_feature_id", "nunique"),
        }
    )
    .sort_values("Fountain Score", ascending=False)
    .reset_index(drop=True)
)
print(enh_50kb_summary)

score_by_enh_n = (
    enh_50kb_summary
    .groupby("n_enhancers_50kb", as_index=False)
    .agg(
        mean_score=("Fountain Score", "mean"),
        std_score=("Fountain Score", "std"),
        n_fountains=("Fountain Score", "count"),
    )
)
print(score_by_enh_n)

