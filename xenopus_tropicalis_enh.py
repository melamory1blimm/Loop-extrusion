def read_narrowpeak(path):
    """
    Reads narrowPeak / BED-like peak file.

    Expected columns:
    chrom, start, end, name, score, strand, signalValue, pValue, qValue, peak
    But works if there are at least 3 columns.
    """
    df = pd.read_csv(
        path,
        sep="\t",
        header=None,
        comment="#",
    )

    base_cols = [
        "chrom", "start", "end", "name", "score", "strand",
        "signalValue", "pValue", "qValue", "peak"
    ]

    n = df.shape[1]
    df.columns = base_cols[:n] + [f"extra_{i}" for i in range(n - len(base_cols))]

    df["chrom"] = df["chrom"].astype(str)
    df["start"] = df["start"].astype(int)
    df["end"] = df["end"].astype(int)

    if "score" not in df.columns:
        df["score"] = 1000

    df["score"] = pd.to_numeric(df["score"], errors="coerce").fillna(0).astype(float)
    df["score"] = df["score"].clip(0, 1000).astype(int)

    if "strand" not in df.columns:
        df["strand"] = "."

    return df


def parse_gtf_attributes(attr):
    """
    Parses GTF attributes:
    gene_id "..."; transcript_id "..."; gene_name "...";
    """
    out = {}
    for item in str(attr).strip().split(";"):
        item = item.strip()
        if not item:
            continue

        if " " in item:
            key, value = item.split(" ", 1)
            out[key] = value.strip().strip('"')

    return out


def read_gtf_transcript_tss(gtf_path, protein_coding_only=False):
    """
    Extract transcript-level TSS from GTF.

    GTF is 1-based inclusive.
    BED output is 0-based half-open.
    """
    cols = [
        "chrom", "source", "feature", "start", "end",
        "score", "strand", "frame", "attributes"
    ]

    gtf = pd.read_csv(
        gtf_path,
        sep="\t",
        comment="#",
        header=None,
        names=cols,
        compression="infer",
    )

    tx = gtf[gtf["feature"] == "transcript"].copy()

    tx["start"] = tx["start"].astype(int)
    tx["end"] = tx["end"].astype(int)
    tx["chrom"] = tx["chrom"].astype(str)

    attrs = tx["attributes"].apply(parse_gtf_attributes)

    tx["gene_id"] = attrs.apply(lambda d: d.get("gene_id"))
    tx["transcript_id"] = attrs.apply(lambda d: d.get("transcript_id"))
    tx["gene_name"] = attrs.apply(lambda d: d.get("gene_name"))
    tx["gene_biotype"] = attrs.apply(lambda d: d.get("gene_biotype") or d.get("gene_type"))
    tx["transcript_biotype"] = attrs.apply(lambda d: d.get("transcript_biotype") or d.get("transcript_type"))

    if protein_coding_only:
        tx = tx[
            (tx["gene_biotype"] == "protein_coding") |
            (tx["transcript_biotype"] == "protein_coding")
        ].copy()

    # TSS as 0-based coordinate
    tx["tss0"] = np.where(
        tx["strand"] == "+",
        tx["start"] - 1,
        tx["end"] - 1,
    ).astype(int)

    tss = tx[
        [
            "chrom", "tss0", "strand",
            "gene_id", "transcript_id", "gene_name",
            "gene_biotype", "transcript_biotype"
        ]
    ].copy()

    # убираем точные дубликаты transcript/TSS
    tss = tss.drop_duplicates(
        subset=["chrom", "tss0", "strand", "gene_id", "transcript_id"]
    ).reset_index(drop=True)

    return tss


def make_tss_windows(tss_df, window_bp=1000):
    """
    Makes TSS-centered promoter windows.
    """
    prom = tss_df.copy()
    prom["start"] = (prom["tss0"] - window_bp).clip(lower=0).astype(int)
    prom["end"] = (prom["tss0"] + window_bp + 1).astype(int)
    return prom


def overlap_any(a, b, a_start="start", a_end="end", b_start="start", b_end="end"):
    """
    Fast boolean overlap test:
    for each interval in a, checks if it overlaps at least one interval in b.

    Intervals are 0-based half-open: [start, end).
    """
    out = np.zeros(len(a), dtype=bool)

    if len(a) == 0 or len(b) == 0:
        return out

    a = a.reset_index(drop=True)
    b = b.reset_index(drop=True)

    for chrom, idx_a in a.groupby("chrom").groups.items():
        if chrom not in set(b["chrom"]):
            continue

        aa = a.loc[idx_a]
        bb = b[b["chrom"] == chrom].copy()

        bs = np.sort(bb[b_start].to_numpy(dtype=int))
        be = np.sort(bb[b_end].to_numpy(dtype=int))

        a_s = aa[a_start].to_numpy(dtype=int)
        a_e = aa[a_end].to_numpy(dtype=int)

        # B.start < A.end
        n_started = np.searchsorted(bs, a_e, side="left")

        # B.end <= A.start
        n_ended = np.searchsorted(be, a_s, side="right")

        has = (n_started - n_ended) > 0
        out[np.asarray(list(idx_a))] = has

    return out


def harmonize_chrom_names_to_reference(df, ref_chroms, chrom_col="chrom"):
    """
    Harmonizes chromosome names to reference set.
    Handles:
    1 <-> chr1 <-> Chr1
    """
    df = df.copy()
    df[chrom_col] = df[chrom_col].astype(str)

    ref_chroms = set(map(str, ref_chroms))
    cur = set(df[chrom_col])

    if len(cur & ref_chroms) > 0:
        return df

    def variants(x):
        x = str(x)
        out = [x]

        if x.startswith("chr"):
            core = x[3:]
            out += [core, "Chr" + core]
        elif x.startswith("Chr"):
            core = x[3:]
            out += [core, "chr" + core]
        else:
            out += ["chr" + x, "Chr" + x]

        return out

    mapping = {}

    for x in cur:
        found = None
        for v in variants(x):
            if v in ref_chroms:
                found = v
                break

        if found is not None:
            mapping[x] = found
        else:
            mapping[x] = x

    df[chrom_col] = df[chrom_col].map(mapping)

    new_overlap = len(set(df[chrom_col]) & ref_chroms)

    if new_overlap == 0:
        print("WARNING: could not harmonize chromosome names.")
        print("Example df chroms:", sorted(list(cur))[:10])
        print("Example ref chroms:", sorted(list(ref_chroms))[:10])
    else:
        print("Chromosome-name harmonization overlap:", new_overlap)

    return df


def to_bed8(df, label, name_prefix=None, score_col="score", strand_col=None):
    """
    Converts interval dataframe to BED8-like table:
    #chrom, chromStart, chromEnd, name, score, strand, thickStart, thickEnd
    """
    out = pd.DataFrame()
    out["#chrom"] = df["chrom"].astype(str)
    out["chromStart"] = df["start"].astype(int)
    out["chromEnd"] = df["end"].astype(int)

    if name_prefix is None:
        name_prefix = label

    out["name"] = [
        f"{i + 1}_{label}"
        for i in range(len(df))
    ]

    if score_col in df.columns:
        out["score"] = pd.to_numeric(df[score_col], errors="coerce").fillna(0).clip(0, 1000).astype(int)
    else:
        out["score"] = 1000

    if strand_col is not None and strand_col in df.columns:
        out["strand"] = df[strand_col].fillna(".").astype(str)
    else:
        out["strand"] = "."

    out["thickStart"] = out["chromStart"]
    out["thickEnd"] = out["chromEnd"]

    return out

def normalize_xentr_chrom(chrom):
    chrom = str(chrom)

