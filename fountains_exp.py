                    if np.sum(wp) <= 0:
                        wp = np.ones_like(wp)

                    z_peak_x = np.average(X_local[z_top], weights=wz)
                    z_peak_y = np.average(Y_local[z_top], weights=wz)

                    p_peak_x = np.average(X_local[p_top], weights=wp)
                    p_peak_y = np.average(Y_local[p_top], weights=wp)

                    peak_dist_kb = np.sqrt(
                        (p_peak_x - z_peak_x) ** 2 +
                        (p_peak_y - z_peak_y) ** 2
                    )

