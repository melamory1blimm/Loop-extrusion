    """
    Из уже готовой таблицы enhancer_hits выбирает все enhancer hits
    для top-n фонтанов по Fountain Score.

    enhancer_hits: long-table, где одна строка = fountain-enhancer pair.
    """

    hits = enhancer_hits.copy()

    if max_distance_bp is not None:
        hits = hits[
            hits["enhancer_distance_to_base_bp"] <= max_distance_bp
        ].copy()

