def plot_probability_model_fit(
    aggregate_Z,
    Z_pred,
    res=5000,
    image_vmin=0.5,
    image_vmax=1.6,
    residual_vmax=None,
):
    Z = np.asarray(aggregate_Z, dtype=float)
    pred = np.asarray(Z_pred, dtype=float)
    residual = Z - pred

    n = Z.shape[0]
    bin_kb = res / 1000.0
    coords_kb = (np.arange(n) - (n - 1) / 2.0) * bin_kb
    extent = [coords_kb.min(), coords_kb.max(), coords_kb.max(), coords_kb.min()]

    if residual_vmax is None:
        vals = residual[np.isfinite(residual)]
        residual_vmax = np.nanquantile(np.abs(vals), 0.99)

    fig, axes = plt.subplots(1, 3, figsize=(14, 4.4))

    im0 = axes[0].imshow(
        Z,
        origin="upper",
        extent=extent,
        cmap="coolwarm",
        vmin=image_vmin,
        vmax=image_vmax,
        interpolation="nearest",
    )
    axes[0].set_title("Data")
    plt.colorbar(im0, ax=axes[0], fraction=0.046)

    im1 = axes[1].imshow(
        pred,
        origin="upper",
        extent=extent,
        cmap="coolwarm",
        vmin=image_vmin,
        vmax=image_vmax,
        interpolation="nearest",
    )
    axes[1].set_title("Analytical model")
    plt.colorbar(im1, ax=axes[1], fraction=0.046)

    im2 = axes[2].imshow(
        residual,
        origin="upper",
        extent=extent,
        cmap="coolwarm",
        vmin=-residual_vmax,
        vmax=residual_vmax,
        interpolation="nearest",
    )
    axes[2].set_title("Residual")
    plt.colorbar(im2, ax=axes[2], fraction=0.046)

    for ax in axes:
        ax.axline((0, 0), slope=1, linestyle="--", linewidth=1, color="black", alpha=0.45)
        ax.axline((0, 0), slope=-1, linestyle=":", linewidth=1, color="black", alpha=0.45)
        ax.set_xlabel("Distance from fountain base, kb")
        ax.set_ylabel("Distance from fountain base, kb")

    plt.tight_layout()
    return fig, axes

